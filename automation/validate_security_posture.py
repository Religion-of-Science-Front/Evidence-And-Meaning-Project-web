from __future__ import annotations

from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]

SKIP_DIRS = {".git", ".venv", "node_modules", "__pycache__"}
SKIP_SUFFIXES = {".png", ".jpg", ".jpeg", ".gif", ".webp", ".pdf", ".zip", ".ico"}

# High-confidence secret shapes only. Documentation may mention token *names* safely;
# this validator looks for credential-like lengths / PEM material.
PATTERNS: list[tuple[str, re.Pattern[str]]] = [
    ("private key material", re.compile(r"-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----")),
    ("GitHub classic PAT", re.compile(r"\bghp_[A-Za-z0-9]{30,}\b")),
    ("GitHub fine-grained PAT", re.compile(r"\bgithub_pat_[A-Za-z0-9_]{40,}\b")),
    ("GitHub OAuth token", re.compile(r"\bgho_[A-Za-z0-9]{30,}\b")),
    ("GitHub server token", re.compile(r"\bghs_[A-Za-z0-9]{30,}\b")),
    ("Cloudflare global key", re.compile(r"\bcfk_[A-Za-z0-9_-]{40,}\b")),
    ("Cloudflare user token", re.compile(r"\bcfut_[A-Za-z0-9_-]{40,}\b")),
    ("Cloudflare account token", re.compile(r"\bcfat_[A-Za-z0-9_-]{40,}\b")),
    ("AWS access key", re.compile(r"\bAKIA[0-9A-Z]{16}\b")),
    ("Stripe live secret", re.compile(r"\bsk_live_[A-Za-z0-9]{20,}\b")),
]

REQUIRED_SECURITY_FILES = [
    "docs/30_founder_and_governance/FOUNDER_SECURITY_ARCHITECTURE.md",
    "docs/80_operations/FOUNDER_ROOT_ACCOUNT_HARDENING_RUNBOOK.md",
    "docs/80_operations/FOUNDER_ROOT_ASSET_REGISTER.md",
    "site/_headers",
]

REQUIRED_HEADER_SNIPPETS = [
    "X-Frame-Options: DENY",
    "X-Content-Type-Options: nosniff",
    "Referrer-Policy:",
    "Permissions-Policy:",
    "Content-Security-Policy:",
]


def iter_text_files():
    for path in ROOT.rglob("*"):
        if not path.is_file():
            continue
        if any(part in SKIP_DIRS for part in path.parts):
            continue
        if path.suffix.lower() in SKIP_SUFFIXES:
            continue
        try:
            data = path.read_bytes()
        except OSError:
            continue
        if b"\x00" in data:
            continue
        try:
            text = data.decode("utf-8")
        except UnicodeDecodeError:
            continue
        yield path, text


def required_security_files() -> list[str]:
    # The Public Front is generated by build_public_front.py and intentionally
    # excludes private Canon docs/. It is identified by its release manifest.
    # Secret scanning and header checks still run in full there.
    if (ROOT / "PUBLIC_RELEASE_MANIFEST.json").exists():
        return [rel for rel in REQUIRED_SECURITY_FILES if not rel.startswith("docs/")]
    return REQUIRED_SECURITY_FILES


def main() -> int:
    errors: list[str] = []

    for rel in required_security_files():
        if not (ROOT / rel).exists():
            errors.append(f"required security file missing: {rel}")

    headers_path = ROOT / "site/_headers"
    if headers_path.exists():
        headers = headers_path.read_text(encoding="utf-8")
        for snippet in REQUIRED_HEADER_SNIPPETS:
            if snippet not in headers:
                errors.append(f"site/_headers missing required control: {snippet}")

    for path, text in iter_text_files():
        rel = path.relative_to(ROOT)
        for label, pattern in PATTERNS:
            if pattern.search(text):
                errors.append(f"possible {label} committed in {rel}")

    if errors:
        for error in errors:
            print(f"ERROR: {error}")
        return 1

    print("PASS: security posture files present; no high-confidence secret patterns detected")
    return 0


if __name__ == "__main__":
    sys.exit(main())
